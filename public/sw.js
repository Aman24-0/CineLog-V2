// public/sw.js
//
// CineLog V2 — Service Worker for Web Push Notifications
// ---------------------------------------------------------------------
// Scope:       '/' (registered from entry-client.tsx)
// Lifetime:    Persistent across browser sessions; survives tab close.
// Activated:   immediately via skipWaiting() + clients.claim() so the
//              SW is ready to receive push events on first visit.
//
// EVENTS HANDLED:
//   install      → skipWaiting() so a new SW takes over from the old
//                  one without waiting for all tabs to close.
//   activate     → clients.claim() so the SW controls the current tab
//                  immediately (otherwise it only controls tabs opened
//                  AFTER it activated).
//   push         → parse the JSON payload and show a system
//                  notification. Payload shape (sent by /api/push/send):
//                    {
//                      title: string,
//                      body?: string,
//                      icon?: string,        // default /favicon.ico
//                      badge?: string,       // default /favicon.ico
//                      tag?: string,         // default "default"
//                      url?: string          // click-through target
//                    }
//   notificationclick → focus an existing tab pointing at `url` if one
//                  exists, otherwise open a new tab. Then close the
//                  notification.
//
// QUIET HOURS:
//   Quiet hours are enforced SERVER-SIDE by /api/push/send (the server
//   reads the user's quiet hours pref and refuses to send during the
//   window). The SW does not need to know about quiet hours — by the
//   time a push event arrives, it has already passed the quiet-hours
//   gate.
//
// WHY A SEPARATE FILE (not generated by workbox / vite-plugin-pwa):
//   CineLog uses vinxi/SolidStart, and the existing build pipeline
//   doesn't include a PWA plugin. A hand-written SW at /public/sw.js
//   is the simplest, most debuggable approach — Vercel serves it as a
//   static asset at the root path, which is exactly what
//   navigator.serviceWorker.register('/sw.js') expects.
//
// SECURITY:
//   The SW runs in a secure context (HTTPS only — Vercel enforces this).
//   It cannot read the page's localStorage or sessionStorage directly
//   (SWs have a separate storage scope), so the VAPID public key +
//   subscription are managed by the page and POSTed to the server.
// ---------------------------------------------------------------------

// ─── install: take over immediately ─────────────────────────────────
self.addEventListener("install", () => {
  self.skipWaiting();
});

// ─── activate: control existing clients immediately ─────────────────
self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

// ─── push: show a notification ──────────────────────────────────────
self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch (e) {
    // Malformed payload — fall back to a sensible default so the user
    // still sees SOMETHING (a silent push would be confusing).
    data = {
      title: "CineLog",
      body: "You have a new notification.",
    };
  }

  const title = data.title || "CineLog";
  const options = {
    body: data.body || "",
    icon: data.icon || "/favicon.ico",
    badge: data.badge || "/favicon.ico",
    tag: data.tag || "default",
    data: data.url ? { url: data.url } : undefined,
    // requireInteraction: keep the notification visible until the user
    // dismisses it, rather than auto-hiding after a few seconds. This
    // matches user intent for release-day reminders (the whole point
    // is to grab attention).
    requireInteraction: true,
  };

  event.waitUntil(self.registration.showNotification(title, options));
});

// ─── notificationclick: focus existing tab or open new one ──────────
self.addEventListener("notificationclick", (event) => {
  event.notification.close();

  const url = (event.notification.data && event.notification.data.url) || "/";

  event.waitUntil(
    self.clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((clientList) => {
        // If a tab is already open at the target URL, focus it.
        for (const client of clientList) {
          if (client.url === url && "focus" in client) {
            return client.focus();
          }
        }
        // Otherwise open a new tab.
        if (self.clients.openWindow) {
          return self.clients.openWindow(url);
        }
        return null;
      })
  );
});

// ─── message: handle page-driven lifecycle commands ─────────────────
// The page can post messages to the SW to trigger an immediate update
// check (after a deploy) or to manually skip waiting.
self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") {
    self.skipWaiting();
  }
});
