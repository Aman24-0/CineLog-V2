// public/sw.js
//
// CineLog V2 — Service Worker for Web Push Notifications + PWA Foundation
// ---------------------------------------------------------------------
// Scope:       '/' (registered from entry-client.tsx)
// Lifetime:    Persistent across browser sessions; survives tab close.
// Activated:   immediately via skipWaiting() + clients.claim() so the
//              SW is ready to receive push events on first visit.
//
// EVENTS HANDLED:
//   install      → skipWaiting() so a new SW takes over from the old
//                  one without waiting for all tabs to close.
//   activate     → clients.claim() so the SW controls the current tab
//                  immediately (otherwise it only controls tabs opened
//                  AFTER it activated).
//   fetch        → passthrough fetch handler. Required for Chrome's PWA
//                  installability criteria (a SW must register a fetch
//                  handler to be considered a "real" PWA). We simply
//                  pass the request through to the network — no
//                  caching layer yet. This is the minimum viable
//                  implementation; a future phase can add a runtime
//                  cache for TMDB images / static assets.
//   push         → parse the JSON payload and show a system
//                  notification. Payload shape (sent by /api/push/send):
//                    {
//                      title: string,
//                      body?: string,
//                      icon?: string,        // default /favicon.ico
//                      badge?: string,       // default /favicon.ico
//                      tag?: string,         // default "default"
//                      url?: string,         // click-through target
//                      requireInteraction?: boolean  // default false
//                    }
//                  The requireInteraction flag is read from the PAYLOAD
//                  (previously hardcoded to true, which made every
//                  notification sticky — annoying for low-priority
//                  reminders). Server-side default in /api/push/send
//                  is false; only release-day reminders set it to true.
//   notificationclick → focus an existing tab pointing at `url` if one
//                  exists, otherwise open a new tab. Then close the
//                  notification.
//   pushsubscriptionchange → fired by the browser when the push
//                  subscription has expired or been invalidated (e.g.
//                  the user cleared site data, or the push service
//                  rotated the endpoint). We attempt to resubscribe
//                  and POST the new subscription to /api/push/subscribe
//                  so the server can replace the stale endpoint. If
//                  resubscription fails, we log cleanly — the next
//                  user-initiated subscription will pick up the slack.
//
// QUIET HOURS:
//   Quiet hours are enforced SERVER-SIDE by /api/push/send (the server
//   reads the user's quiet hours pref and refuses to send during the
//   window). The SW does not need to know about quiet hours — by the
//   time a push event arrives, it has already passed the quiet-hours
//   gate.
//
// WHY A SEPARATE FILE (not generated by workbox / vite-plugin-pwa):
//   CineLog uses vinxi/SolidStart, and the existing build pipeline
//   doesn't include a PWA plugin. A hand-written SW at /public/sw.js
//   is the simplest, most debuggable approach — Vercel serves it as a
//   static asset at the root path, which is exactly what
//   navigator.serviceWorker.register('/sw.js') expects.
//
// SECURITY:
//   The SW runs in a secure context (HTTPS only — Vercel enforces this).
//   It cannot read the page's localStorage or sessionStorage directly
//   (SWs have a separate storage scope), so the VAPID public key +
//   subscription are managed by the page and POSTed to the server.
//
// RUNTIME CACHING (Phase 7 Task 1)
// ---------------------------------
//   The fetch handler implements three strategies keyed by request type:
//
//   1. CACHE-FIRST  — static assets (JS/CSS/fonts/icons) under our own
//      origin. These are content-addressed by Vite's hashed filenames
//      so a cached copy is always safe to serve forever. Falls back to
//      the network only on cache miss, then caches the response.
//
//   2. NETWORK-FIRST — HTML navigations (requests whose destination is
//      "document"). The SW always tries the network first so users get
//      the latest HTML on first load. On network failure (offline), it
//      falls back to the cached app shell so the SPA still loads.
//
//   3. STALE-WHILE-REVALIDATE — same-origin /api/* calls AND cross-
//      origin TMDB image CDN requests. Serve cached response
//      immediately if present, then fetch a fresh copy in the
//      background to update the cache for next time. This gives
//      instant poster loads on repeat visits while keeping the cache
//      fresh.
//
//   The app shell (a small set of critical URLs) is PRECACHED on
//   install so the app loads offline even on a cold SW install. The
//   precache list is intentionally minimal — full assets are populated
//   lazily by the runtime cache as the user navigates.
//
//   Bounded cache eviction: each cache has a MAX_ENTRIES cap. When
//   exceeded, the oldest entries are evicted (LRU-ish — we delete by
//   iteration order, which Cache API preserves as insertion order).
//   This prevents the cache from growing unboundedly over months of
//   use, which would otherwise trigger storage eviction by the browser.
// ---------------------------------------------------------------------

// ─── Cache names (versioned so a deploy can bust old caches) ────────
// Bumped from v7 → v8 to force cache invalidation after the PKCE cookie
// adapter rewrite. Users with a cached v7 SW were running the OLD
// browser code (implicit document.cookie fallback) even after the new
// deploy — the cacheFirstStatic strategy was serving stale JS bundles.
// Bumping the version causes the activate handler to delete all v7
// caches, forcing the browser to fetch fresh assets on next navigation.
//
// v8 → v10 (Task 13): the auth callback component was rewritten to
// remove the manual `exchangeCodeForSession` call (which raced with
// `detectSessionInUrl`). Returning users with a cached v8 JS bundle
// would still have the old callback code that calls
// `exchangeCodeForSession` manually — bumping to v10 invalidates
// their cached bundles and forces them to download the new
// passive-listener version. Skipping v9 to keep the version
// monotonically ahead of any intermediate deploys.
//
// v10 → v11 (Task 14): the passive-listener approach (v10) FAILED in
// production — `detectSessionInUrl: true` was silently failing the
// PKCE exchange, and the callback was waiting 10s for a `SIGNED_IN`
// event that never came. We've now:
//   • Set `detectSessionInUrl: false` in `src/lib/supabase/browser.ts`.
//   • Rewrote `src/routes/auth/callback.tsx` to MANUALLY call
//     `exchangeCodeForSession(code, { flowId })` with try/catch +
//     real error display.
// Returning users with a cached v10 bundle still have the passive-
// listener code (no manual exchange) AND the `detectSessionInUrl: true`
// browser client config — both of which are broken together. Bumping
// to v11 invalidates their cached bundles and forces them to download
// the new explicit-exchange version.
//
// v11 → v13-localstorage (Task 15): the explicit-exchange approach
// (v11) STILL failed on mobile browsers because the underlying
// `@supabase/ssr` cookie adapter was fundamentally broken on mobile
// (SameSite=Lax cookies dropped on cross-site OAuth redirects by
// Safari ITP and Chrome Android incognito). Task 15 abandons
// `@supabase/ssr` entirely and switches to the STANDARD
// `@supabase/supabase-js` `createClient` with `localStorage` as the
// session + PKCE verifier storage backend. localStorage is first-party
// only and NEVER blocked by cookie policies.
//
// Returning users with a cached v11 bundle still have:
//   • The `@supabase/ssr` cookie-based browser client (broken on mobile).
//   • The explicit-exchange callback component (now reverted to dumb
//     listener since `detectSessionInUrl: true` is reliable again with
//     localStorage).
// Bumping to `v13-localstorage` (skipping v12 to keep the version
// monotonically ahead of any intermediate deploys, and using a
// descriptive suffix to make this version memorable in devtools)
// invalidates their cached bundles and forces them to download the
// new localStorage-based version.
//
// NOTE: The version string is used in cache names like
// `cinelog-static-v13-localstorage`. Cache API names allow hyphens
// and letters, so this is safe — but it does mean old caches with
// numeric-only versions (`cinelog-static-v11`) will be matched by
// the `!key.endsWith("-v13-localstorage")` filter and deleted on
// activate, which is exactly what we want.
const CACHE_VERSION = "v14-html-timeout";
const CACHE_STATIC = `cinelog-static-${CACHE_VERSION}`;
const CACHE_HTML = `cinelog-html-${CACHE_VERSION}`;
const CACHE_RUNTIME = `cinelog-runtime-${CACHE_VERSION}`;

// ─── App-shell URLs to precache on install ──────────────────────────
//   Only the bare minimum: the entry HTML and the offline fallback.
//   Vite-built JS/CSS chunks are NOT precached because their hashed
//   names change every deploy — we'd just be wasting storage. The
//   runtime cache fills them in on first navigation.
const APP_SHELL_URLS = ["/", "/offline.html"];

// ─── Cache size caps (per cache) ────────────────────────────────────
const MAX_STATIC_ENTRIES = 80;
const MAX_HTML_ENTRIES = 8;
const MAX_RUNTIME_ENTRIES = 200;

// ─── HTML navigation fetch timeout ──────────────────────────────────
//   Phase 14 Chunk 8 hotfix — COLD-START LOADING BAR FIX
//
//   The browser's native loading indicator (the progress bar in the
//   tab chrome) stays active for as long as the navigation fetch is
//   in flight. On a cold start — Vercel serverless cold start, slow
//   DNS, flaky 3G, Supabase session check hanging — the server can
//   take 5–10+ seconds to respond, so the browser loading bar sits
//   at 60–70% the entire time and looks "stuck".
//
//   The previous networkFirstHtml() strategy waited indefinitely for
//   the network. We now race the fetch against this timeout. If the
//   network doesn't respond in 3 seconds:
//     1. Fall back to the cached HTML / app shell immediately so the
//        browser loading bar finishes and the SPA can hydrate.
//     2. The original network fetch keeps running in the background
//        and populates the cache for the next visit (we don't abort
//        it — AbortController on a navigation fetch can cause weird
//        half-rendered states in some browsers).
//
//   3 seconds is the sweet spot: fast enough that the user never
//   sees a "stuck" bar for more than 3s, slow enough that a normal
//   fast connection (typical HTML response is <1s) is never
//   interrupted. The in-app useAuth cold-start timeout (8s) and the
//   useUserLibrary safety timer (12s) provide deeper layers of
//   protection for the in-app spinner.
const HTML_NAV_TIMEOUT_MS = 3000;

/**
 * Evict the oldest entries from a cache until its size is <= max.
 * Called after every cache.put() so the cap is enforced continuously.
 *
 * The Cache API preserves insertion order, so deleting the first
 * entries is an LRU-ish eviction (it's not a true LRU because reading
 * doesn't reorder, but it's good enough to bound storage growth).
 */
async function trimCache(cacheName, maxEntries) {
  const cache = await caches.open(cacheName);
  const keys = await cache.keys();
  if (keys.length <= maxEntries) return;
  // Delete oldest (first inserted) entries until under cap.
  const excess = keys.length - maxEntries;
  for (let i = 0; i < excess; i++) {
    await cache.delete(keys[i]);
  }
}

// ─── install: precache app shell + take over immediately ────────────
self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE_STATIC);
      // Precache app shell URLs. Use addAll — if ANY URL fails, the
      // whole install fails (intentional: we want a working shell).
      // We catch per-URL so a missing /offline.html (added later)
      // doesn't block the SW from installing.
      await Promise.all(
        APP_SHELL_URLS.map(async (url) => {
          try {
            await cache.add(new Request(url, { cache: "reload" }));
          } catch (err) {
            // Non-fatal: the runtime cache will populate on first
            // navigation. We log so it's visible in devtools.
            console.warn(`[SW] precache miss for ${url}:`, err);
          }
        })
      );
      self.skipWaiting();
    })()
  );
});

// ─── activate: claim clients + clean up old cache versions ──────────
self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // Delete any cache from a previous CACHE_VERSION so we don't
      // leak storage after a deploy. Caches for the current version
      // are kept.
      const allKeys = await caches.keys();
      await Promise.all(
        allKeys
          .filter(
            (key) =>
              key.startsWith("cinelog-") && !key.endsWith(`-${CACHE_VERSION}`)
          )
          .map((key) => caches.delete(key))
      );
      await self.clients.claim();
    })()
  );
});

// ─── fetch: runtime caching strategies ──────────────────────────────
//
// Three strategies keyed by request type (see the RUNTIME CACHING
// block at the top of this file for the full rationale):
//
//   • Navigation (mode === "navigate")           → NETWORK-FIRST (HTML)
//   • Same-origin static asset (script/style/font/image) → CACHE-FIRST
//   • Same-origin /api/* OR TMDB image CDN       → STALE-WHILE-REVALIDATE
//   • Everything else                            → passthrough (no cache)
//
// We NEVER cache:
//   • POST/PUT/DELETE (mutations must hit the server)
//   • Supabase auth endpoints (would break session refresh)
//   • Push subscription endpoints
// These are filtered out by the method check + URL pattern check.
self.addEventListener("fetch", (event) => {
  const req = event.request;

  // Only handle GET — mutations (POST/PUT/DELETE/PATCH) always go to
  // the network. Caching them would cause duplicate-writes when the
  // SW serves a cached response.
  if (req.method !== "GET") return;

  const url = new URL(req.url);

  // Skip non-http(s) schemes (chrome-extension://, data:, blob:, etc.)
  // — the SW can't meaningfully cache them and trying to fetch them
  // throws. Let the browser handle them with its default behavior.
  if (url.protocol !== "http:" && url.protocol !== "https:") return;

  // Skip Supabase auth + push subscription endpoints — caching these
  // would break session refresh and push subscription lifecycle.
  // We match on path prefix to be conservative.
  const isSupabaseAuthOrPush =
    url.pathname.startsWith("/auth/v1/") ||
    url.pathname.startsWith("/rest/v1/") && url.pathname.includes("push_subscriptions") ||
    url.pathname.startsWith("/realtime/v1/");

  // Skip /api/push/* and /api/email/* (mutation endpoints, even on GET
  // they return dynamic per-user state we don't want to cache).
  const isPushOrEmailApi =
    url.pathname.startsWith("/api/push/") ||
    url.pathname.startsWith("/api/email/");

  if (isSupabaseAuthOrPush || isPushOrEmailApi) return;

  // ─── Strategy 1: NETWORK-FIRST for HTML navigations ───────────────
  if (req.mode === "navigate") {
    event.respondWith(networkFirstHtml(req));
    return;
  }

  // ─── Strategy 2: CACHE-FIRST for same-origin static assets ────────
  if (url.origin === self.location.origin) {
    const dest = req.destination;
    if (
      dest === "style" ||
      dest === "script" ||
      dest === "font" ||
      dest === "image"
    ) {
      event.respondWith(cacheFirstStatic(req));
      return;
    }
    // Same-origin /api/* → SWR
    if (url.pathname.startsWith("/api/")) {
      event.respondWith(staleWhileRevalidate(req));
      return;
    }
    // Other same-origin GETs (e.g. /manifest.json, /favicon.ico) → SWR
    event.respondWith(staleWhileRevalidate(req));
    return;
  }

  // ─── Strategy 3: STALE-WHILE-REVALIDATE for TMDB image CDN ───────
  // TMDB posters are served from image.tmdb.org. They're large, rarely
  // change, and the user sees them on every page — perfect SWR targets.
  // Cross-origin fonts (Google Fonts) are also SWR'd.
  if (
    url.hostname === "image.tmdb.org" ||
    url.hostname.endsWith(".image.tmdb.org")
  ) {
    event.respondWith(staleWhileRevalidate(req));
    return;
  }
});

/**
 * NETWORK-FIRST (with timeout) for HTML navigations.
 *
 *   Phase 14 Chunk 8 hotfix — COLD-START LOADING BAR FIX
 *   ─────────────────────────────────────────────────────────────────
 *   Previously this function did `await fetch(req)` with no timeout.
 *   On a cold start (Vercel serverless cold start, slow DNS, flaky
 *   3G), the server can take 5–10+ seconds to respond. The browser's
 *   native loading indicator stays active the entire time, sitting at
 *   60–70% and looking "stuck" — the user has to manually refresh.
 *
 *   We now race the network fetch against HTML_NAV_TIMEOUT_MS (3s):
 *     • If the network responds first → cache + return (happy path,
 *       same as before).
 *     • If the timeout fires first → fall back to the cached HTML /
 *       app shell immediately so the browser loading bar finishes and
 *       the SPA can hydrate. The network fetch is NOT aborted — it
 *       keeps running in the background and populates the cache for
 *       the next visit (aborting a navigation fetch can cause weird
 *       half-rendered states in some browsers).
 *     • If the network fails (offline) AND we have no cache → fall
 *       back to /offline.html, then rethrow as a last resort.
 *
 * We only cache "ok" responses (status 200) — redirects (3xx) and
 * errors (4xx/5xx) are passed through without caching so a transient
 * 502 doesn't get stuck in the cache.
 */
async function networkFirstHtml(req) {
  const cache = await caches.open(CACHE_HTML);

  // Race the network fetch against the cold-start timeout. We use a
  // custom timeout promise (rather than AbortController) because
  // aborting a navigation fetch can leave the browser in a weird
  // half-rendered state on some engines — we want the fetch to keep
  // running in the background and populate the cache, we just stop
  // WAITING for it.
  //
  // The background cache update is attached directly to the fetch
  // promise so it fires regardless of whether the timeout won the
  // race. This means even if we serve the cached app shell (because
  // the network was slow), the fresh network response will still
  // populate the cache for the NEXT visit.
  const networkPromise = fetch(req)
    .then((resp) => {
      // Always cache a successful network response, even if the
      // timeout already fired and we served a cached fallback to
      // the page. This keeps the cache fresh for the next visit.
      if (resp && resp.ok && resp.status === 200) {
        cache.put(req, resp.clone()).then(() =>
          trimCache(CACHE_HTML, MAX_HTML_ENTRIES)
        );
      }
      return resp;
    })
    .catch((err) => {
      // Network failed — re-throw so the catch block below can
      // handle the offline fallback. The cache was not updated.
      throw err;
    });

  const timeoutPromise = new Promise((_, reject) => {
    setTimeout(() => {
      reject(new Error("HTML_NAV_TIMEOUT"));
    }, HTML_NAV_TIMEOUT_MS);
  });

  try {
    const networkResp = await Promise.race([
      networkPromise,
      timeoutPromise
    ]);
    // The network won the race. The cache was already updated inside
    // networkPromise's .then() handler, so we just return the response.
    return networkResp;
  } catch (err) {
    // Either the network failed (offline / 5xx) OR the timeout fired.
    // In both cases, try to serve a cached response so the browser
    // loading bar finishes and the SPA can hydrate.
    //
    // Network-first means we PREFER the network, but on a cold start
    // a 3-second-old cached HTML is vastly better than a 10-second
    // stuck loading bar. The background fetch (still in flight if the
    // timeout fired) will update the cache for next time.

    // Try the cached version of this exact URL first (deep links).
    const cached = await cache.match(req);
    if (cached) return cached;

    // Then try the app shell (lets the SPA hydrate and route
    // client-side to the deep-linked path).
    const shell = await cache.match("/");
    if (shell) return shell;

    // If the timeout fired (not a network error) AND we have no
    // cache, we still want to let the network request continue —
    // but we can't hold the browser loading bar open forever. Fall
    // through to the offline page as a last resort; the user can
    // refresh to retry.
    const offline = await caches.match("/offline.html");
    if (offline) return offline;

    // Nothing cached at all — rethrow so the browser shows its native
    // offline page (better than a blank response). If the timeout
    // fired (err.message === "HTML_NAV_TIMEOUT") the original network
    // fetch is still in flight in the background; the next navigation
    // will benefit from whatever it caches.
    throw err;
  }
}

/**
 * CACHE-FIRST for same-origin static assets.
 *
 *   1. Check the cache. If hit, return immediately (instant load).
 *   2. On miss, fetch from network, cache the response, return it.
 *   3. On network error AND cache miss, return a synthetic 504 so the
 *      browser knows the asset is unavailable (better than an
 *      unhandled rejection).
 *
 * Vite hashes filenames, so a cached asset is always the correct
 * version — there's no staleness risk. This is why we can cache
 * "forever" (until the MAX cap evicts).
 */
async function cacheFirstStatic(req) {
  const cache = await caches.open(CACHE_STATIC);
  const cached = await cache.match(req);
  if (cached) return cached;
  try {
    const networkResp = await fetch(req);
    if (networkResp && networkResp.ok) {
      cache.put(req, networkResp.clone());
      trimCache(CACHE_STATIC, MAX_STATIC_ENTRIES);
    }
    return networkResp;
  } catch (err) {
    // Cache miss + network failure — return a 504 Gateway Timeout so
    // the browser doesn't show a confusing blank asset. The page will
    // render with the missing asset (a missing JS chunk is fatal, but
    // a missing image is not).
    return new Response("Offline and not cached", {
      status: 504,
      statusText: "Gateway Timeout",
      headers: { "Content-Type": "text/plain" }
    });
  }
}

/**
 * STALE-WHILE-REVALIDATE for /api/* calls and TMDB images.
 *
 *   1. Check the cache. If hit, serve it immediately AND fire a
 *      background fetch to update the cache for next time.
 *   2. On cache miss, fetch from network, cache, return.
 *   3. On cache miss + network failure, return a 504.
 *
 * The background revalidation is `fetch(req).then(cache.put)` — it's
 * not awaited, so the user gets the stale response instantly. Errors
 * in the background fetch are swallowed (the next request will try
 * again with the same stale-then-revalidate flow).
 *
 * We only cache GET responses with status 200 — error responses are
 * passed through uncached so transient failures don't get stuck.
 */
async function staleWhileRevalidate(req) {
  const cache = await caches.open(CACHE_RUNTIME);
  const cached = await cache.match(req);

  // Fire the background revalidation. We use a separate promise so
  // errors don't propagate to the response — the user just sees the
  // stale (or fresh network) response, and the cache silently updates.
  const revalidate = fetch(req)
    .then((networkResp) => {
      if (networkResp && networkResp.ok && networkResp.status === 200) {
        cache.put(req, networkResp.clone());
        trimCache(CACHE_RUNTIME, MAX_RUNTIME_ENTRIES);
      }
      return networkResp;
    })
    .catch(() => {
      // Background revalidation failed (offline, 5xx, etc.) — silently
      // swallow. The cached response (if any) is already being served.
      // The next request will retry the revalidation.
    });

  // If we have a cached response, serve it immediately — do NOT await
  // the revalidation. The user gets instant feedback.
  if (cached) {
    // Revalidate in the background (don't await).
    event_queueMicrotask(() => revalidate);
    return cached;
  }

  // No cached response — we MUST wait for the network (no choice).
  try {
    const networkResp = await revalidate;
    if (networkResp) return networkResp;
  } catch (err) {
    // revalidate already caught its own errors, but defensive: if it
    // somehow rejected, fall through to the 504 below.
  }
  return new Response("Offline and not cached", {
    status: 504,
    statusText: "Gateway Timeout",
    headers: { "Content-Type": "text/plain" }
  });
}

/**
 * Helper to schedule a microtask without referencing the global `queueMicrotask`
 * name (some bundlers rename it). We define a local alias for clarity.
 */
function event_queueMicrotask(fn) {
  Promise.resolve().then(fn);
}

// ─── push: show a notification ──────────────────────────────────────
self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch (e) {
    // Malformed payload — fall back to a sensible default so the user
    // still sees SOMETHING (a silent push would be confusing).
    data = {
      title: "CineLog",
      body: "You have a new notification.",
    };
  }

  const title = data.title || "CineLog";
  const options = {
    body: data.body || "",
    icon: data.icon || "/favicon.ico",
    badge: data.badge || "/favicon.ico",
    tag: data.tag || "default",
    data: data.url ? { url: data.url } : undefined,
    // requireInteraction: when true, the notification stays visible
    // until the user dismisses it (instead of auto-hiding after a
    // few seconds). This is appropriate for high-priority reminders
    // (e.g. "Your tracked show releases today!") but annoying for
    // low-priority pings. The server decides per-notification by
    // setting `requireInteraction: true|false` in the push payload.
    // We READ it from the payload (defaulting to false) instead of
    // hardcoding it to true — the previous behaviour made every
    // notification sticky, which trained users to dismiss them
    // reflexively.
    requireInteraction: data.requireInteraction === true,
  };

  event.waitUntil(self.registration.showNotification(title, options));
});

// ─── notificationclick: focus existing tab or open new one ──────────
self.addEventListener("notificationclick", (event) => {
  event.notification.close();

  const url = (event.notification.data && event.notification.data.url) || "/";

  event.waitUntil(
    self.clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((clientList) => {
        // If a tab is already open at the target URL, focus it.
        for (const client of clientList) {
          if (client.url === url && "focus" in client) {
            return client.focus();
          }
        }
        // Otherwise open a new tab.
        if (self.clients.openWindow) {
          return self.clients.openWindow(url);
        }
        return null;
      })
  );
});

// ─── pushsubscriptionchange: resubscribe + notify server ───────────
// Fired by the browser when the push subscription has expired or been
// invalidated. Browsers can rotate the endpoint at any time (e.g. when
// the user clears site data, or the push service rotates keys). If we
// don't resubscribe, the server will keep sending pushes to a dead
// endpoint and the user silently stops receiving notifications.
//
// FLOW:
//   1. If `event.newSubscription` is provided by the browser (the new
//      "automatic" subscription), use it directly. Otherwise, attempt
//      to resubscribe via PushManager.subscribe() — but this requires
//      the VAPID public key, which is not stored in the SW. The page
//      fetches it from Supabase's app_config table; the SW cannot
//      easily do the same (no Supabase client, no auth cookie context
//      for the RLS-protected row). So if the browser doesn't provide
//      a new subscription, we log cleanly and let the page handle
//      resubscription on the user's next visit (the
//      usePushSubscription() hook's checkSubscription() detects the
//      missing subscription and the user sees the toggle flip to OFF).
//   2. POST the new subscription to /api/push/subscribe so the server
//      can REPLACE the stale endpoint. We include the old endpoint in
//      the body so the server can find and delete the old row before
//      inserting the new one.
//   3. If anything fails, log cleanly — we don't want a transient
//      network error to crash the SW.
self.addEventListener("pushsubscriptionchange", (event) => {
  const oldSubscription = event.oldSubscription;
  const newSubscription = event.newSubscription;

  const handleChange = async () => {
    // Log the change unconditionally so it's visible in devtools —
    // this is the "at least logs the change cleanly" fallback.
    console.info("[SW] pushsubscriptionchange fired", {
      oldEndpoint: oldSubscription?.endpoint ?? null,
      newEndpoint: newSubscription?.endpoint ?? null,
    });

    // If the browser provided a new subscription automatically, POST
    // it to the server immediately. This is the happy path.
    if (newSubscription) {
      try {
        await fetch("/api/push/subscribe", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            subscription: newSubscription,
            oldEndpoint: oldSubscription?.endpoint ?? null,
          }),
        });
        console.info("[SW] pushsubscriptionchange: new subscription posted to server");
      } catch (err) {
        console.warn("[SW] pushsubscriptionchange: failed to POST new subscription", err);
      }
      return;
    }

    // No new subscription provided by the browser. We can't resubscribe
    // ourselves because we don't have the VAPID key in the SW scope.
    // The page's usePushSubscription() hook will detect the missing
    // subscription on the user's next visit and re-prompt them to
    // re-enable notifications (which calls subscribe() with the VAPID
    // key it fetches from app_config). This is the correct UX — silent
    // re-subscription without the user's knowledge would be surprising
    // and could violate platform push policies (which require explicit
    // user consent for subscription).
    console.info(
      "[SW] pushsubscriptionchange: no new subscription provided. The page will re-subscribe on the user's next visit."
    );
  };

  event.waitUntil(handleChange());
});

// ─── message: handle page-driven lifecycle commands ─────────────────
// The page can post messages to the SW to trigger an immediate update
// check (after a deploy) or to manually skip waiting.
self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") {
    self.skipWaiting();
  }
});
